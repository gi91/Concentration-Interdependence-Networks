# ---- complete null-model results (OA.4): built from the csv -------------------
f <- file.path(DIR_TAB, "tabOA2_null_models_full.csv")
if (file.exists(f)) {
  d <- utils::read.csv(f, check.names = FALSE)
  p3 <- function(x) ifelse(x < 0.001, "$<0.001$", sprintf("%.3f", x))
  f2 <- function(x) sprintf("%.2f", x); f1 <- function(x) sprintf("%.1f", x)
  rows <- character(0); prev <- ""
  for (i in seq_len(nrow(d))) {
    if (d$panel[i] != prev) {
      if (prev != "") rows <- c(rows, "\\midrule")
      rows <- c(rows, sprintf("\\multicolumn{13}{l}{\\textit{%s}} \\\\", d$panel[i]))
      prev <- d$panel[i]
    }
    rows <- c(rows, paste0(paste(d$network[i], f2(d$G_rec[i]), p3(d$p_perm_rec[i]),
      f1(d$z_mantel_rec[i]), f1(d$z_avail_rec[i]), p3(d$p_rew_rec[i]),
      p3(d$p_dbcm_rec[i]), f1(d$z_dbcm_rec[i]),
      if (!is.null(d$p_fixed_pairs)) paste(p3(d$p_fixed_pairs[i]), p3(d$p_fixed_partners[i]), sep = " & ") else "-- & --",
      f2(d$G_c3[i]), p3(d$p_perm_c3[i]),
      p3(d$p_rew_c3[i]), p3(d$p_rew_oneway[i]), sep = " & "), " \\\\"))
  }
  dst <- file.path(TABD, "OA4_null_models", "null_models_full.tex")
  dir.create(dirname(dst), recursive = TRUE, showWarnings = FALSE)
  writeLines(c("% generated by scripts/15_paper_assets.R from output/tables/tabOA2_null_models_full.csv",
    "\\begin{fitwidth}",
    "\\begin{tabular}{lcccccccccccccc}", "\\toprule",
    " & \\multicolumn{9}{c}{Reciprocal component} & \\multicolumn{3}{c}{Circuits of length 3} & One-way \\\\",
    "\\cmidrule(lr){2-10}\\cmidrule(lr){11-13}\\cmidrule(lr){14-14}",
