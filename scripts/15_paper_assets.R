# escape bare %, $-$ for numeric minus signs outside math (idempotent)
fix_cell <- function(x) {
  x <- gsub("\\\\\\\\%", "\\\\%", x)                       # legacy "\\%" -> "\%"
  x <- gsub("(?<!\\\\)%", "\\\\%", x, perl = TRUE)
  ifelse(grepl("$", x, fixed = TRUE), x,
         gsub("(^|[\\s(\\[])-(?=[0-9.])", "\\1$-$", x, perl = TRUE))
}
fix_line <- function(l) {
  if (!grepl("&", l, fixed = TRUE)) return(fix_cell(l))
  end <- sub("^.*?(\\s*\\\\\\\\\\s*)$", "\\1", l)
  body <- sub("\\s*\\\\\\\\\\s*$", "", l)
  paste0(paste(fix_cell(strsplit(body, "&", fixed = TRUE)[[1]]), collapse = "&"),
         if (grepl("\\\\\\\\\\s*$", l)) " \\\\" else "")
}
# keep only the tabular of a table written by write_tex_table()
extract_tabular <- function(file, header = NULL) {
  L <- readLines(file, warn = FALSE)
  a <- grep("^\\\\begin\\{tabular\\}", L); b <- grep("^\\\\end\\{tabular\\}", L)
  L <- L[a:b]
  top <- grep("^\\\\toprule", L)[1]; mid <- grep("^\\\\midrule", L)[1]
  if (!is.null(header)) L <- c(L[1:top], header, L[mid:length(L)])
  # fix body rows only (between the first \midrule and \bottomrule)
  bot <- grep("^\\\\bottomrule", L)[1]; mid <- grep("^\\\\midrule", L)[1]
  idx <- seq(mid + 1, bot - 1)
  L[idx] <- vapply(L[idx], fix_line, character(1), USE.NAMES = FALSE)
  L[seq(1, mid)] <- gsub("\\\\\\\\%", "\\\\%", L[seq(1, mid)])
  c("\\begin{fitwidth}", L, "\\end{fitwidth}")
}

